internal static class CoreAudio
{
    public const uint ClsCtxAll = 0x17;

    // AUDIO_VOLUME_NOTIFICATION_DATA: GUID guidEventContext (16) | BOOL bMuted (4) | float fMasterVolume (4) | ...
    private const int MutedOffset = 16;
    private const int MasterVolumeOffset = 20;

    public static (float Level, bool Muted) ReadVolumeNotification(IntPtr data) =>
        (BitConverter.Int32BitsToSingle(Marshal.ReadInt32(data, MasterVolumeOffset)),
         Marshal.ReadInt32(data, MutedOffset) != 0);
}
